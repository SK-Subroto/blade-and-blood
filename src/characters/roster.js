// Defaults shared by every move, filled in once at load.
(function fillDefaults() {
	const base = {
		light: { stun: 28, push: 5, energy: 8 },
		heavy: { stun: 34, push: 11, lift: -7, energy: 12, heavy: true, cooldown: 35 },
		air: { stun: 26, push: 5, energy: 8 },
		special: { cost: 50, special: true },
		super: { cost: 100, special: true, big: true },
	};
	for (const key in ROSTER) {
		const r = ROSTER[key];
		r.key = key;
		r.stats = Object.assign({ health: 100, speed: 1, jump: 17, gravity: 1, damage: 1, airJumps: 1, airDashes: 1, dashCooldown: 1, energyGain: 1, energyRegen: 1, blockEnergy: 1 }, r.stats);
		for (const m in base) if (m !== 'air' || r.moves.air) r.moves[m] = Object.assign({}, base[m], r.moves[m]);
		// guard break (↓ ← + heavy): a slower, unblockable version of the heavy slash
		const hv = r.moves.heavy;
		r.moves.breaker = Object.assign({}, hv, { name: 'Guard Break', hold: hv.hold + 2, damage: Math.round(hv.damage * 0.8), unblockable: true, breaker: true, cost: 25, lunge: Math.max(hv.lunge || 0, 4), armor: false, cooldown: 0 });
		for (const s in r.sprites) {
			const sp = r.sprites[s];
			if (!sp.hold) sp.hold = 5;
			sp.loop = ['idle', 'run', 'jump', 'fall', 'defend', 'roll'].includes(s);
		}
	}
})();
