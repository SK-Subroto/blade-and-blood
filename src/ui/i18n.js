// ---------- Languages: English and Bengali (বাংলা) ----------
// Every piece of text the player sees comes through tx('key'). Bengali uses Bengali digits
// (০১২…) everywhere numbers are shown, and the bundled Baloo Da 2 font (src/fonts/).

let LANG = 'en';
const BN_DIGITS = '০১২৩৪৫৬৭৮৯';

function localDigits(s) {
	s = String(s);
	return LANG === 'bn' ? s.replace(/[0-9]/g, (d) => BN_DIGITS[d]) : s;
}

// tx('key', { name: 'MACK' }) fills {name}; digits follow the language
function tx(key, vars) {
	return localDigits(txRaw(key, vars));
}
// the same, but digits stay as they are (keyboard keys like "Numpad 1")
function txRaw(key, vars) {
	let s = STRINGS[LANG][key];
	if (s === undefined) s = STRINGS.en[key];
	if (s === undefined) return key;
	if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? '' : vars[k]));
	return s;
}

