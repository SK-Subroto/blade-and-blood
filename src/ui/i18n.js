// a fighter's text in the current language
function fighterText(key) {
	const cfg = ROSTER[key];
	const en = {
		name: cfg.name,
		short: cfg.short,
		title: cfg.title,
		blurb: cfg.blurb,
		passiveName: cfg.passive.name,
		passiveText: cfg.passive.text,
		quote: cfg.quote,
		special: cfg.moves.special.name,
		super: cfg.moves.super.name,
	};
	const b = LANG === 'bn' && ROSTER_BN[key];
	if (!b) return en;
	return { name: b[0], short: b[1], title: b[2], blurb: localDigits(b[3]), passiveName: b[4], passiveText: localDigits(b[5]), quote: b[6], special: b[7], super: b[8] };
}
function moveName(key, which) {
	return fighterText(key)[which];
}
function levelName(level) {
	return tx(`level.${level}`);
}

