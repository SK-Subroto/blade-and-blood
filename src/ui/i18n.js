// ---------- applying a language to the page ----------
// Static text in index.html carries data-i18n="key" (text), data-i18n-raw (keyboard keys,
// digits kept) and data-i18n-aria (aria-label).
function setLanguage(code, { quiet = false } = {}) {
	LANG = STRINGS[code] ? code : 'en';
	document.documentElement.lang = LANG;
	document.title = tx('app.title');
	document.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = tx(el.dataset.i18n)));
	document.querySelectorAll('[data-i18n-raw]').forEach((el) => (el.textContent = txRaw(el.dataset.i18nRaw)));
	document.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', tx(el.dataset.i18nAria)));
	document.querySelectorAll('[data-i18n-ph]').forEach((el) => el.setAttribute('placeholder', tx(el.dataset.i18nPh)));
	// the canvas needs the Bengali font loaded before it can draw with it
	if (LANG === 'bn' && document.fonts) document.fonts.load('700 20px "BB Bangla Canvas"', 'অ').catch(() => {});
	if (!quiet && typeof onLanguageChanged === 'function') onLanguageChanged();
}
